#2.  Área de un triángulo:
#Pide al usuario la base y la altura de un triángulo. 
#Calcula el área del triángulo (área = (base * altura) / 2) e imprime el resultado.

print("bienvenido al programa")
altura = int(input("ingresa la altura de triangulo: "))
base = int(input("ingrese la base del triangulo: "))
area = (altura * base)/2
print(f"su resultado es {area}")