#3.  Conversión de temperatura:
#Pide al usuario una temperatura en grados Celsius. 
#Convierte la temperatura a grados Fahrenheit (Fahrenheit = (Celsius * 9/5) + 32) e imprime el resultado.

print("bienvenido al programa")
celsius = int(input("ingrese los grados a convertir en Fahrenheit: "))

Fahrenheit = (celsius * 9/5) + 32

print(f"la temperatur en Fahrenheit es {Fahrenheit} ")
